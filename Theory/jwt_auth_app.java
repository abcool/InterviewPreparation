package com.example.jwtapp.controller;

import com.example.jwtapp.entity.User;
import com.example.jwtapp.repository.UserRepository;
import com.example.jwtapp.security.JwtUtil;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.security.authentication.*;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.web.bind.annotation.*;

import java.util.Map;

@RestController
@RequestMapping("/auth")
public class AuthController {
    @Autowired
    private UserRepository userRepository;

    @Autowired
    private AuthenticationManager authenticationManager;

    @Autowired
    private JwtUtil jwtUtil;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @PostMapping("/register")
    public String register(@RequestBody Map<String, String> request) {
        String username = request.get("username");
        String password = passwordEncoder.encode(request.get("password"));
        userRepository.save(new User(null, username, password));
        return jwtUtil.generateToken(username);
    }

    @PostMapping("/login")
    public String login(@RequestBody Map<String, String> request) {
        authenticationManager.authenticate(
                new UsernamePasswordAuthenticationToken(request.get("username"), request.get("password")));
        return jwtUtil.generateToken(request.get("username"));
    }

    @PostMapping("/logout")
    public String logout(@RequestHeader("Authorization") String authHeader) {
        String token = authHeader.substring(7);
        jwtUtil.invalidateToken(token);
        return "Logged out successfully.";
    }
}

